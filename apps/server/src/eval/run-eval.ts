/**
 * Golden-set evaluation harness. Usage (from the repo root):
 *
 *   pnpm eval                      # report on every eval/golden/*.json
 *   pnpm eval --update-snapshots   # re-baseline anchors after an intended parser change
 *   pnpm eval --record-runs        # run every org preset lens via the org model, save raw output to eval/runs/
 *   pnpm eval --out eval/report.md # also write the report to a file
 *
 * Exits non-zero when a stored anchor is no longer stable or reading order
 * regressed below its baseline, so it can gate parser changes in CI.
 * See eval/README.md.
 */
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import type { LensOutputItem, LensSpec } from "@paper-xray/contracts";
import { findEvidenceRange, sanitizeLensItems } from "@paper-xray/contracts";
import { verifyAndFilterAgentAnnotations } from "../evidence/apply-verification.js";
import { PRESET_LENSES } from "../lenses/presets.js";
import { lensItemsToCandidates } from "../lenses/run-model-lens.js";
import { callChatModel, isModelConfigured } from "../lenses/model-client.js";
import { buildLensSystemPrompt, buildLensUserMessage, parseLensModelOutput } from "@paper-xray/contracts";
import { EVAL_DIR, listGoldenNames, loadGolden, readSnapshot, snapshotPath, type LoadedGolden } from "./golden.js";
import { charMapCoverage, checkAnchor, matchSpans, readingOrderScore, sampleAnchors } from "./metrics.js";

const ANCHOR_SAMPLE_COUNT = 40;

const args = new Set(process.argv.slice(2));
const outIndex = process.argv.indexOf("--out");
const outPath = outIndex !== -1 ? process.argv[outIndex + 1] : null;

function pct(n: number, d: number): string {
  return d === 0 ? "n/a" : `${((100 * n) / d).toFixed(1)}%`;
}

async function recordRuns(g: LoadedGolden): Promise<void> {
  if (!isModelConfigured()) throw new Error("--record-runs needs PPIO_API_KEY (the org model endpoint)");
  const dir = path.join(EVAL_DIR, "runs", g.name);
  await mkdir(dir, { recursive: true });
  for (const spec of PRESET_LENSES) {
    const raw = await callChatModel([
      { role: "system", content: buildLensSystemPrompt(spec) },
      { role: "user", content: buildLensUserMessage(g.normalizedText) },
    ]);
    const items = parseLensModelOutput(raw, spec.maxAnnotations);
    await writeFile(
      path.join(dir, `${spec.id}.json`),
      JSON.stringify({ lensId: spec.id, lensVersion: spec.version, recordedAt: new Date().toISOString(), items }, null, 2) + "\n",
    );
    console.log(`recorded ${g.name}/${spec.id}: ${items.length} item(s)`);
  }
}

async function readRuns(name: string): Promise<Array<{ lensId: string; items: LensOutputItem[] }>> {
  const dir = path.join(EVAL_DIR, "runs", name);
  let files: string[];
  try {
    files = (await readdir(dir)).filter((f) => f.endsWith(".json"));
  } catch {
    return [];
  }
  const runs = [];
  for (const f of files.sort()) {
    const data = JSON.parse(await readFile(path.join(dir, f), "utf8")) as { lensId: string; items: unknown };
    runs.push({ lensId: data.lensId, items: sanitizeLensItems(data.items, Infinity) });
  }
  return runs;
}

async function evaluate(name: string, lines: string[]): Promise<boolean> {
  const g = await loadGolden(name);
  let ok = true;
  lines.push(`## ${name}`, "");
  if (!g.hashMatches) lines.push(`⚠️ ${g.golden.pdf} doesn't match the golden contentHash — the PDF changed.`, "");

  // 1. Reading order (reassembly quality), against human-transcribed snippets.
  const ro = readingOrderScore(g.normalizedText, g.golden.readingOrder.snippets);
  lines.push(
    "| Metric | Value |",
    "| --- | --- |",
    `| Reading-order snippets found | ${ro.found} / ${ro.total} (${pct(ro.found, ro.total)}) |`,
    `| …of those, in correct order | ${ro.inOrder} / ${ro.found} (${pct(ro.inOrder, ro.found)}) |`,
  );

  // 2. CharMap coverage (what can be highlighted at all).
  const cov = charMapCoverage(g.normalizedText, g.charMap);
  lines.push(`| CharMap coverage (non-whitespace) | ${pct(cov.mapped, cov.total)} |`);

  // 3. Anchor stability across parser versions.
  let snapshot = await readSnapshot(name);
  if (args.has("--update-snapshots") || !snapshot) {
    snapshot = {
      note: "Generated by `pnpm eval --update-snapshots`. Each anchor must keep resolving to the same text after any parser change (docs/02-decisions.md #2). Re-baseline only for an intended change, and plan a migration for stored annotations.",
      anchors: sampleAnchors(g.normalizedText, ANCHOR_SAMPLE_COUNT),
      readingOrderBaseline: { found: ro.found, inOrder: ro.inOrder },
    };
    await writeFile(snapshotPath(name), JSON.stringify(snapshot, null, 2) + "\n");
    lines.push(`| Anchor snapshot | written (${snapshot.anchors.length} anchors) |`);
  } else {
    const statuses = snapshot.anchors.map((a) => checkAnchor(g.normalizedText, a));
    const stable = statuses.filter((s) => s === "stable").length;
    const relocated = statuses.filter((s) => s === "relocated").length;
    lines.push(`| Anchors stable | ${stable} / ${statuses.length} (relocated ${relocated}, lost ${statuses.length - stable - relocated}) |`);
    if (stable < statuses.length) ok = false;
    const base = snapshot.readingOrderBaseline;
    if (ro.found < base.found || ro.inOrder < base.inOrder) {
      lines.push(`| Reading-order regression | baseline ${base.found} found / ${base.inOrder} in order |`);
      ok = false;
    }
  }
  lines.push("");
  if (ro.missing.length) lines.push(`Missing snippets: ${ro.missing.map((s) => `"${s}"`).join(", ")}`, "");
  if (ro.outOfOrder.length) lines.push(`Out of order: ${ro.outOfOrder.map((s) => `"${s}"`).join(", ")}`, "");

  // 4. Lens output: evidence verification rates, and precision/recall where gold labels exist.
  const runs = await readRuns(name);
  if (runs.length === 0) {
    lines.push("No recorded lens runs (`pnpm eval --record-runs` with an org model key creates them).", "");
  } else {
    lines.push(
      "| Lens | Items | Quote found verbatim | Passed verification | Gold | Precision | Recall | F1 |",
      "| --- | --- | --- | --- | --- | --- | --- | --- |",
    );
    for (const run of runs) {
      const spec: LensSpec =
        PRESET_LENSES.find((p) => p.id === run.lensId) ??
        ({ ...PRESET_LENSES[0], id: run.lensId, scope: "all", maxAnnotations: Infinity } as LensSpec);
      const candidates = lensItemsToCandidates({
        items: run.items,
        spec: { ...spec, maxAnnotations: Infinity },
        docId: name,
        normalizedText: g.normalizedText,
        nodes: g.nodes,
        ownerId: null,
      });
      const verified = verifyAndFilterAgentAnnotations({
        candidates,
        normalizedText: g.normalizedText,
        nodes: g.nodes,
        scope: spec.scope,
        strictScope: true,
      });
      const gold = g.golden.lensGold.annotations
        .filter((a) => a.lensId === run.lensId)
        .map((a) => findEvidenceRange(g.normalizedText, a.evidenceText))
        .filter((r) => r !== null);
      const m = gold.length ? matchSpans(verified.map((v) => v.evidenceSpan), gold) : null;
      lines.push(
        `| ${run.lensId} | ${run.items.length} | ${pct(candidates.length, run.items.length)} | ${pct(verified.length, run.items.length)} | ${gold.length || "unlabelled"} | ${m ? m.precision.toFixed(2) : "—"} | ${m ? m.recall.toFixed(2) : "—"} | ${m ? m.f1.toFixed(2) : "—"} |`,
      );
    }
    lines.push("");
  }
  lines.push(
    "Semantic check (does the evidence support the comment?) is not implemented, so it is not measured — `semanticMatch` stays null.",
    "",
  );
  return ok;
}

async function main(): Promise<void> {
  const names = await listGoldenNames();
  if (args.has("--record-runs")) {
    for (const name of names) await recordRuns(await loadGolden(name));
  }
  const lines = ["# Paper X-Ray evaluation report", "", `Generated ${new Date().toISOString()}`, ""];
  let ok = true;
  for (const name of names) ok = (await evaluate(name, lines)) && ok;
  const report = lines.join("\n");
  console.log(report);
  if (outPath) await writeFile(path.resolve(process.cwd(), outPath), report + "\n");
  if (!ok) {
    console.error("\nEvaluation FAILED: anchors moved or reading order regressed (see above).");
    process.exit(1);
  }
}

await main();
